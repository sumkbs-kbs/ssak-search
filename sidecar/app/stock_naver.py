def parse_korean_number(text: str) -> Optional[int]:
    """Parse Korean-formatted number (e.g. '170,100' or '1.23만' → 12300)."""
    if not text:
        return None
    text = text.strip().replace(",", "").replace(" ", "")

    # Handle units: 조, 억, 만
    if "조" in text:
        n = re.sub(r"[^0-9.]", "", text)
        try:
            return int(float(n) * 1_000_000_000_000)
        except ValueError:
            return None
    if "억" in text:
        n = re.sub(r"[^0-9.]", "", text)
        try:
            return int(float(n) * 100_000_000)
        except ValueError:
            return None
    if "만" in text:
        n = re.sub(r"[^0-9.]", "", text)
        try:
            return int(float(n) * 10_000)
        except ValueError:
            return None

    # Plain number
    try:
        return int(text)
    except ValueError:
        return None


