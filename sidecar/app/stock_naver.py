async def fetch_stock_data(
    query: str,
    *,
    include_chart: bool = False,
    include_financials: bool = False,
    timeout: int = 15,
) -> dict[str, Any]:
    """
    Fetch Korean stock data from Naver Finance using Scrapling.

    Returns a dict matching StockResponse pydantic model.
    """
    start = time.time()
    result: dict[str, Any] = {
        "name": "", "code": "", "exchange": "KOSPI",
        "price": 0, "currency": "KRW",
        "change": 0, "change_percent": 0.0, "direction": "flat",
        "volume": None, "market_cap": None,
        "per": None, "eps": None,
        "market_status": "closed",
        "chart_data": [],
        "source": "naver_finance_html",
        "success": False, "error": None,
        "response_time_ms": 0,
    }

    # --- Step 1: Find stock code ---
    stock_code = lookup_stock_code(query)
    if stock_code is None:
        company = extract_company_name(query)
        if company:
            stock_code = search_stock_code_naver(company, timeout=timeout)
    if stock_code is None:
        elapsed = (time.time() - start) * 1000
        result["success"] = False
        result["error"] = f"Could not find stock code for query: {query}"
        result["response_time_ms"] = int(elapsed)
        return result

    result["code"] = stock_code
    result["exchange"] = detect_exchange(stock_code)

    # --- Step 2: Try JSON API first (fastest) ---
    try:
        import httpx
        api_url = NAVER_STOCK_API.format(code=stock_code)
        api_resp = httpx.get(
            api_url,
            timeout=timeout,
            headers={
                "User-Agent": (
                    "Mozilla/5.0 (iPhone; CPU iPhone OS 17_0 like Mac OS X) "
                    "AppleWebKit/605.1.15"
                ),
                "Referer": "https://finance.naver.com/",
            },
        )
        if api_resp.status_code == 200:
            api_data = api_resp.json()
            datas = api_data.get("datas", [])
            if datas and len(datas) > 0:
                d = datas[0]
                result["name"] = d.get("stockName", "")
                result["price"] = parse_korean_number(d.get("closePrice", "0")) or 0
                result["change"] = parse_korean_number(d.get("compareToPreviousClosePrice", "0")) or 0
                result["change_percent"] = float(d.get("fluctuationsRatio", "0"))
                result["direction"] = (
                    "up" if result["change"] > 0
                    else "down" if result["change"] < 0
                    else "flat"
                )
                result["open_price"] = parse_korean_number(d.get("openingPrice"))
                result["high_price"] = parse_korean_number(d.get("highPrice"))
                result["low_price"] = parse_korean_number(d.get("lowPrice"))
                result["prev_close"] = parse_korean_number(d.get("previousClose"))
                result["volume"] = parse_korean_number(d.get("accumulatedVolume"))
                result["market_cap"] = parse_korean_number(d.get("marketValue"))
                result["market_status"] = "open" if d.get("marketStatus") == "OPEN" else "closed"
                result["source"] = "naver_finance_api"
                result["success"] = True
                elapsed = (time.time() - start) * 1000
                result["response_time_ms"] = int(elapsed)
                return result
    except Exception as e:
        logger.info(f"Naver Finance API failed, falling back to HTML scraping: {e}")

    # --- Step 3: HTML Scraping with Scrapling (fallback) ---
    scraper = AdaptiveScraper(headless=True, solve_cloudflare=False)
    url = NAVER_FINANCE_MAIN.format(code=stock_code)

    page, method, elapsed_ms = scraper.fetch_page(
        url,
        timeout_seconds=timeout,
        headless=True,
        use_stealth=True,
        use_dynamic=True,
    )

    if page is None:
        # Fallback to httpx for basic HTML
        logger.info("Scrapling failed, trying httpx direct...")
        html = HttpxFallbackFetcher.fetch(url, request_timeout=timeout)
        if html is None:
            elapsed = (time.time() - start) * 1000
            result["error"] = f"All fetchers failed for {url}"
            result["response_time_ms"] = int(elapsed)
            return result
        page = html
        method = "httpx_fallback"

    logger.info(f"Fetched {url} using {method} ({elapsed_ms:.0f}ms)")

    # --- Step 4: Parse stock data from HTML ---
    html_str = str(page) if hasattr(page, '__str__') else (page if isinstance(page, str) else "")

    # Stock name from title
    title_match = re.search(r"<title>([^<]+)</title>", html_str, re.IGNORECASE)
    if title_match:
        result["name"] = title_match.group(1).replace(" : 네이버 금융", "").strip()

    # Current price — from the 'no_today' area
    # Pattern: <span class="no_up">170,100</span> or no_down
    price_match = re.search(
        r'class="no_(?:up|down)"[^>]*>\s*<span[^>]*>\s*([0-9,]+)\s*</span>',
        html_str, re.IGNORECASE,
    )
    if not price_match:
        # Simpler pattern
        price_match = re.search(
            r'no_(?:up|down)[^>]*>.*?([0-9,]+)\s*<',
            html_str, re.IGNORECASE | re.DOTALL,
        )
    if price_match:
        result["price"] = parse_korean_number(price_match.group(1)) or 0

    # Direction from class
    if 'class="no_up"' in html_str or 'class="no_up ' in html_str:
        result["direction"] = "up"
    elif 'class="no_down"' in html_str or 'class="no_down ' in html_str:
        result["direction"] = "down"

    # Change amount and percent
    change_match = re.search(
        r'class="(?:up|down|no_up|no_down)"[^>]*>([\s\S]*?)</span>',
        html_str, re.IGNORECASE,
    )
    if change_match:
        change_text = change_match.group(1)
        # Extract "1,500" and "0.87" patterns
        num_match = re.search(r'([0-9,]+)\s*<', change_text)
        pct_match = re.search(r'([+-]?[0-9.]+)%', change_text)
        if num_match:
            result["change"] = parse_korean_number(num_match.group(1)) or 0
        if pct_match:
            result["change_percent"] = float(pct_match.group(1))

    # 시가/고가/저가/전일종가 from the sise table
    sise_table = re.search(
        r'<table[^>]*summary=["\']?[^"\']*시세[^"\']*["\']?[^>]*>([\s\S]*?)</table>',
        html_str, re.IGNORECASE,
    )
    if sise_table:
        table_html = sise_table.group(1)
        # Parse table rows: th/td pairs
        rows = re.findall(
            r'<th[^>]*>(.*?)</th>\s*<td[^>]*>(.*?)</td>',
            table_html, re.IGNORECASE | re.DOTALL,
        )
        for th, td in rows:
            th_clean = re.sub(r'<[^>]+>', '', th).strip()
            td_clean = re.sub(r'<[^>]+>', '', td).strip()
            td_num = parse_korean_number(td_clean)
            if "시가" in th_clean:
                result["open_price"] = td_num
            elif "고가" in th_clean:
                result["high_price"] = td_num
            elif "저가" in th_clean:
                result["low_price"] = td_num
            elif "종가" in th_clean or "전일" in th_clean or "이전" in th_clean:
                result["prev_close"] = td_num

    # 거래량
    volume_match = re.search(
        r'거래량[^<]*<[^>]*>\s*([0-9,]+)',
        html_str, re.IGNORECASE,
    )
    if volume_match:
        result["volume"] = parse_korean_number(volume_match.group(1))

    # 시가총액
    mcap_match = re.search(
        r'시가총액[^<]*<[^>]*>\s*([0-9,]+)',
        html_str, re.IGNORECASE,
    )
    if mcap_match:
        result["market_cap"] = parse_korean_number(mcap_match.group(1))

    # PER / EPS
    per_match = re.search(
        r'PER[^<]*<[^>]*>\s*([0-9.]+)',
        html_str, re.IGNORECASE,
    )
    if per_match:
        try:
            result["per"] = float(per_match.group(1))
        except ValueError:
            pass
    eps_match = re.search(
        r'EPS[^<]*<[^>]*>\s*([0-9,]+)',
        html_str, re.IGNORECASE,
    )
    if eps_match:
        result["eps"] = parse_korean_number(eps_match.group(1))

    result["success"] = True
    result["source"] = f"naver_finance_html_{method}"

    # --- Optional: Chart data ---
    if include_chart:
        try:
            chart_data = await fetch_daily_chart(stock_code, timeout=timeout)
            if chart_data:
                result["chart_data"] = chart_data
        except Exception as e:
            logger.warning(f"Chart fetch failed: {e}")

    elapsed = (time.time() - start) * 1000
    result["response_time_ms"] = int(elapsed)
    return result


async def fetch_daily_chart(
    stock_code: str,
    days: int = 7,
    timeout: int = 10,
) -> list[dict[str, Any]]:
    """
    Fetch daily price chart data from Naver Finance sheet page.

    Returns list of {date, close, open, high, low, volume} dicts.
    """
    scraped_data: list[dict[str, Any]] = []
    try:
        import httpx
        url = NAVER_FINANCE_SHEET.format(code=stock_code)
        resp = httpx.get(
            url,
            timeout=timeout,
            headers={
                "User-Agent": (
                    "Mozilla/5.0 (iPhone; CPU iPhone OS 17_0 like Mac OS X) "
                    "AppleWebKit/605.1.15"
                ),
                "Referer": "https://finance.naver.com/",
            },
            follow_redirects=True,
        )
        if resp.status_code != 200:
            return scraped_data

        html = resp.text

        # Parse the daily price table
        table_match = re.search(
            r'<table[^>]*summary=["\']?[^"\']*시세[^"\']*["\']?[^>]*>([\s\S]*?)</table>',
            html, re.IGNORECASE,
        )
        if not table_match:
            return scraped_data

        table_html = table_match.group(1)

        # Find all rows (skip header)
        rows = re.findall(r'<tr[^>]*>([\s\S]*?)</tr>', table_html, re.IGNORECASE)
        for row in rows[1:days + 1]:  # Skip header row
            cells = re.findall(r'<td[^>]*>([\s\S]*?)</td>', row, re.IGNORECASE)
            if len(cells) >= 7:
                date_str = re.sub(r'<[^>]+>', '', cells[0]).strip()
                close = parse_korean_number(re.sub(r'<[^>]+>', '', cells[1]))
                open_p = parse_korean_number(re.sub(r'<[^>]+>', '', cells[3]))
                high = parse_korean_number(re.sub(r'<[^>]+>', '', cells[4]))
                low = parse_korean_number(re.sub(r'<[^>]+>', '', cells[5]))
                volume = parse_korean_number(re.sub(r'<[^>]+>', '', cells[6]))

                if close and date_str:
                    scraped_data.append({
                        "date": date_str,
                        "close": close,
                        "open": open_p or 0,
                        "high": high or 0,
                        "low": low or 0,
                        "volume": volume or 0,
                    })
    except Exception as e:
        logger.warning(f"Chart data fetch failed: {e}")

    return scraped_data


