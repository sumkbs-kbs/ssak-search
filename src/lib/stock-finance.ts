/**
 * Naver API 응답 → StockData 변환.
 * 가격은 항상 KRW 기준 (달러 오역 방지).
 */
function buildStockData(api: NaverStockApiResponse['datas'][0], exchange: string): StockData | null {
  const priceStr = api.closePrice.replace(/,/g, '')
  const price = parseInt(priceStr, 10)
  if (isNaN(price) || price <= 0) return null

  const changeStr = api.compareToPreviousClosePrice.replace(/,/g, '')
  const change = parseInt(changeStr, 10)
  const changePercent = parseFloat(api.fluctuationsRatio)
  const direction: 'up' | 'down' | 'flat' = change > 0 ? 'up' : change < 0 ? 'down' : 'flat'

  const volumeStr = api.accumulatedTradingVolume?.replace(/,/g, '') || '0'
  const volume = parseInt(volumeStr, 10)

  const marketCapStr = api.marketValueFull?.replace(/,/g, '') || '0'
  const marketCap = parseInt(marketCapStr, 10)

  return {
    name: api.stockName,
    ticker: api.itemCode,
    exchange,
    price,
    currency: 'KRW',
    change,
    change_percent: changePercent,
    direction,
    // Extended fields
    volume,
    marketCap,
    high_price: parseInt(api.highPrice?.replace(/,/g, '') || '0', 10) || undefined,
    low_price: parseInt(api.lowPrice?.replace(/,/g, '') || '0', 10) || undefined,
    open_price: parseInt(api.openPrice?.replace(/,/g, '') || '0', 10) || undefined,
    // previousClose는 API에 없으므로 closePrice - compareToPreviousClosePrice로 계산
    prev_close: price !== 0 && change !== 0 ? price - change : undefined,
    market_status: api.marketStatus === 'OPEN' ? 'open' : 'closed',
  }
}

// ============================================================
// Content Builder — search result content 문자열
// ============================================================

function buildContent(stock: StockData): string {
  const parts: string[] = [stock.name]

  const marketStatus = stock.market_status === 'open' ? '실시간' : '장마감'
  parts.push(`${marketStatus} ${stock.price.toLocaleString()}원`)

  if (stock.change !== 0) {
    const dir = stock.direction === 'up' ? '▲' : stock.direction === 'down' ? '▼' : '→'
    parts.push(`${dir} ${Math.abs(stock.change).toLocaleString()}원 (${stock.change_percent >= 0 ? '+' : ''}${stock.change_percent}%)`)
  }

  parts.push(`시가 ${stock.open_price?.toLocaleString() || '-'}원`)
  parts.push(`고가 ${stock.high_price?.toLocaleString() || '-'}원`)
  parts.push(`저가 ${stock.low_price?.toLocaleString() || '-'}원`)

  if (stock.volume) {
    parts.push(`거래량 ${stock.volume.toLocaleString()}주`)
  }
  if (stock.marketCap) {
    // 시가총액을 조 단위로 변환
    const 조 = stock.marketCap / 1000000000000
    const 억 = (stock.marketCap % 1000000000000) / 100000000
    const mcapStr = 조 >= 1
      ? `${조.toFixed(1)}조${억 > 0 ? ` ${Math.round(억)}억` : ''}원`
      : `${Math.round(억)}억원`
    parts.push(`시가총액 ${mcapStr}`)
  }

  return truncateToTokens(parts.join(' | '), 500)
}

