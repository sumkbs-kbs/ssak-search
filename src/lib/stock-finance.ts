/**
 * Detect exchange (KOSPI/KOSDAQ) from stock code using actual KRX listed code sets.
 * Falls back to prefix heuristic for unknown codes.
 */
function detectExchange(code: string): string {
  if (KOSPI_CODES.has(code)) return 'KOSPI'
  if (KOSDAQ_CODES.has(code)) return 'KOSDAQ'
  // Unknown code — use prefix heuristic fallback.
  const firstDigit = code.charAt(0)
  if (firstDigit === '0' || firstDigit === '1') return 'KOSPI'
  return 'KOSDAQ'
}
