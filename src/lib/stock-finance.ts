/**
 * Naver Finance 실시간 시세 API 호출.
 * polling.finance.naver.com은 Cloudflare Workers에서 직접 호출 가능.
 * fetchWithTimeout 대신 직접 fetch 사용 (env 의존성 제거).
 */
async function fetchRealtimePrice(
  stockCode: string,
  _env?: Env,
  timeoutMs = 8000,
): Promise<NaverStockApiResponse['datas'][0] | null> {
  try {
    const url = `https://polling.finance.naver.com/api/realtime/domestic/stock/${stockCode}`
    const controller = new AbortController()
    const timer = setTimeout(() => controller.abort(), timeoutMs)

    const resp = await fetch(url, {
      signal: controller.signal,
      headers: {
        'User-Agent': 'Mozilla/5.0 (iPhone; CPU iPhone OS 17_0 like Mac OS X) AppleWebKit/605.1.15',
        Accept: 'application/json',
        Referer: 'https://finance.naver.com/',
      },
    })

    clearTimeout(timer)

    if (!resp.ok) {
      logger.warn(`[StockFinance] API returned ${resp.status} for ${stockCode}`)
      return null
    }

    const data: NaverStockApiResponse = await resp.json()
    if (!data.datas || data.datas.length === 0) return null

    return data.datas[0]
  } catch (err) {
    logger.warn(`[StockFinance] Realtime price fetch failed for ${stockCode}:`, { error: toError(err) })
    return null
  }
}

