/**
 * 주기(예: 1일 1회) Naver Finance HTML 페이지를 스크래핑하여
 * adaptive signature를 저장/갱신. polling API가 실패할 때
 * HTML fallback으로 사용.
 *
 * 사용 예:
 *   // 최초: 시그니처 저장
 *   const sig = await captureStockPageSignature('068270', env)
 *   await STORAGE.put('stock_sig_068270', JSON.stringify(sig))
 *
 *   // 이후: 저장된 시그니처로 HTML 파싱
 *   const saved = JSON.parse(await STORAGE.get('stock_sig_068270'))
 *   const price = await extractStockPriceAdaptive('068270', saved, env)
 */
export async function captureStockPageSignature(
  stockCode: string,
  env?: Env,
): Promise<Record<string, unknown> | null> {
  try {
    const url = `https://finance.naver.com/item/main.naver?code=${stockCode}`
    const resp = await fetchWithTimeout(env, url, {
      headers: {
        'User-Agent': 'Mozilla/5.0 (iPhone; CPU iPhone OS 17_0 like Mac OS X) AppleWebKit/605.1.15',
        Accept: 'text/html',
        Referer: 'https://finance.naver.com/',
      },
    }, 10000)

    if (!resp.ok) return null
    const html = await resp.text()

    // Adaptive scraper로 주요 요소 시그니처 캡처
    const { createSnapshot } = await import('./adaptive-scraper')
    const targets = [
      { name: 'stock_price', selector: 'p.no_today' },
      { name: 'stock_table', selector: 'table[summary*="시세"]' },
      { name: 'market_cap', selector: '#_market_sum' },
    ]
    const snapshots = await createSnapshot(html, targets)

    return {
      stockCode,
      capturedAt: Date.now(),
      snapshots,
      htmlLength: html.length,
    }
  } catch (err) {
    logger.warn('[StockFinance] Signature capture failed:', { error: toError(err) })
    return null
  }
}

/**
 * Adaptive signature를 사용해 HTML fallback 파싱.
 * polling API 실패 시 호출.
 */
export async function extractStockPriceAdaptive(
  stockCode: string,
  savedSignature: Record<string, unknown>,
  env?: Env,
): Promise<StockData | null> {
  try {
    const url = `https://finance.naver.com/item/main.naver?code=${stockCode}`
    const resp = await fetchWithTimeout(env, url, {
      headers: {
        'User-Agent': 'Mozilla/5.0 (iPhone; CPU iPhone OS 17_0 like Mac OS X) AppleWebKit/605.1.15',
        Accept: 'text/html',
        Referer: 'https://finance.naver.com/',
      },
    }, 10000)

    if (!resp.ok) return null
    const html = await resp.text()

    // Try to find the price from the HTML using the Naver page structure
    // Pattern: <span class="no_down" or class="no_up">170,100</span>
    const priceMatch = html.match(/class="no_(?:up|down)"[^>]*>\s*([0-9,]+)\s*</)
    const prevCloseMatch = html.match(/전일종가[^<]*<[^>]*>([^<]+)/i)
    const marketCapMatch = html.match(/시가총액[^<]*<[^>]*>([^<]+)/i)

    if (!priceMatch) return null

    const price = parseInt(priceMatch[1].replace(/,/g, ''), 10)
    if (isNaN(price)) return null

    const prevClose = prevCloseMatch
      ? parseInt(prevCloseMatch[1].replace(/,/g, ''), 10)
      : undefined

    const exchange = detectExchange(stockCode)

    return {
      name: '',
      ticker: stockCode,
      exchange,
      price,
      currency: 'KRW',
      change: prevClose ? price - prevClose : 0,
      change_percent: prevClose && prevClose > 0
        ? Math.round(((price - prevClose) / prevClose) * 10000) / 100
        : 0,
      direction: prevClose
        ? price > prevClose ? 'up' : price < prevClose ? 'down' : 'flat'
        : 'flat',
      marketCap: marketCapMatch
        ? parseInt(marketCapMatch[1].replace(/,/g, ''), 10)
        : undefined,
      prev_close: prevClose,
      market_status: 'closed',
    }
  } catch (err) {
    logger.warn('[StockFinance] Adaptive extraction failed:', { error: toError(err) })
    return null
  }
}
