import { describe, it, expect } from 'vitest'
import type { CreateKeyRequest, CreateKeyResponse } from '../../src/lib/api-key-do'

// ============================================================
// Type validation tests
// ============================================================
describe('ApiKey Types', () => {
  it('CreateKeyRequest type is valid', () => {
    const req: CreateKeyRequest = {
      name: 'Test Key',
      scope: 'read',
      expiresInDays: 365,
      owner: '__default__',
    }
    expect(req.name).toBe('Test Key')
    expect(req.scope).toBe('read')
  })

  it('supports all key scopes', () => {
    const scopes = ['read', 'write', 'admin'] as const
    for (const scope of scopes) {
      const req: CreateKeyRequest = { name: 'Key', scope }
      expect(req.scope).toBe(scope)
    }
  })

  it('defaults scope to undefined (will be set by DO)', () => {
    const req: CreateKeyRequest = { name: 'Test Key' }
    expect(req.scope).toBeUndefined()
  })
})

// ============================================================
// Key generation tests (pure logic verification)
// ============================================================
describe('API Key format', () => {
  it('key follows expected format pattern', () => {
    // API keys generated by the DO should match: sk-<base64url>
    const keyPattern = /^sk-[A-Za-z0-9_-]{20,50}$/
    
    // Simulate the key generation logic
    const generateKey = (): string => {
      const chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_'
      let key = 'sk-'
      for (let i = 0; i < 40; i++) {
        key += chars[Math.floor(Math.random() * chars.length)]
      }
      return key
    }

    // Generate multiple keys and verify format
    for (let i = 0; i < 10; i++) {
      const key = generateKey()
      expect(key).toMatch(keyPattern)
      expect(key.startsWith('sk-')).toBe(true)
    }
  })

  it('generates unique keys', () => {
    const keys = new Set<string>()
    for (let i = 0; i < 100; i++) {
      const chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_'
      let key = 'sk-'
      for (let j = 0; j < 40; j++) {
        key += chars[Math.floor(Math.random() * chars.length)]
      }
      keys.add(key)
    }
    // All 100 generated keys should be unique
    expect(keys.size).toBe(100)
  })
})

// ============================================================
// SHA-256 hash tests (using Web Crypto API)
// ============================================================
describe('SHA-256 hashing', () => {
  it('produces consistent hashes for the same input', async () => {
    async function sha256(msg: string): Promise<string> {
      const data = new TextEncoder().encode(msg)
      const hash = await crypto.subtle.digest('SHA-256', data)
      return Array.from(new Uint8Array(hash))
        .map((b) => b.toString(16).padStart(2, '0'))
        .join('')
    }

    const hash1 = await sha256('test-key-123')
    const hash2 = await sha256('test-key-123')
    expect(hash1).toBe(hash2)
  })

  it('produces different hashes for different inputs', async () => {
    async function sha256(msg: string): Promise<string> {
      const data = new TextEncoder().encode(msg)
      const hash = await crypto.subtle.digest('SHA-256', data)
      return Array.from(new Uint8Array(hash))
        .map((b) => b.toString(16).padStart(2, '0'))
        .join('')
    }

    const hash1 = await sha256('key-1')
    const hash2 = await sha256('key-2')
    expect(hash1).not.toBe(hash2)
  })

  it('produces 64 character hex string', async () => {
    async function sha256(msg: string): Promise<string> {
      const data = new TextEncoder().encode(msg)
      const hash = await crypto.subtle.digest('SHA-256', data)
      return Array.from(new Uint8Array(hash))
        .map((b) => b.toString(16).padStart(2, '0'))
        .join('')
    }

    const hash = await sha256('test-key')
    expect(hash).toHaveLength(64)
    expect(/^[0-9a-f]{64}$/.test(hash)).toBe(true)
  })
})

// ============================================================
// ULID format check
// ============================================================
describe('ULID generation', () => {
  it('produces unique identifiers', () => {
    const ids = new Set<string>()
    const generateUlid = (): string => {
      const ts = Date.now().toString(36).padStart(10, '0')
      const random = Array.from({ length: 8 }, () =>
        Math.floor(Math.random() * 36).toString(36)
      ).join('')
      return ts + random
    }

    for (let i = 0; i < 1000; i++) {
      ids.add(generateUlid())
    }
    expect(ids.size).toBe(1000)
  })

  it('keys contain prefix for identification', () => {
    const keyId = 'sk_' + Date.now().toString(36)
    expect(keyId.startsWith('sk_')).toBe(true)
  })
})
